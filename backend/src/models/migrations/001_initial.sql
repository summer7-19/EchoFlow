CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) NOT NULL PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  display_name VARCHAR(80) NOT NULL UNIQUE,
  avatar_url VARCHAR(512) NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audio_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  audio_id VARCHAR(64) NOT NULL UNIQUE,
  user_id CHAR(36) NOT NULL,
  file_path VARCHAR(255) NOT NULL,
  original_name VARCHAR(128) NOT NULL,
  mime_type VARCHAR(128) NOT NULL,
  duration DECIMAL(10,2) NULL,
  file_size BIGINT UNSIGNED NOT NULL,
  status ENUM('UPLOADED','TRANSCRIBING','PARSED','FAILED') NOT NULL DEFAULT 'UPLOADED',
  category ENUM('MEDICATION','SOP','QUIZ','MEMO','INTERVIEW','TRANSCRIPT') NULL,
  transcript_json JSON NOT NULL,
  error_message TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_audio_created_at (created_at),
  INDEX idx_audio_status (status)
  ,INDEX idx_audio_owner_created (user_id, created_at),
  CONSTRAINT fk_audio_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS scene_payloads (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  audio_id VARCHAR(64) NOT NULL,
  category ENUM('MEDICATION','SOP','QUIZ','MEMO','INTERVIEW','TRANSCRIPT') NOT NULL,
  payload_json JSON NOT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_scene_audio (audio_id),
  CONSTRAINT fk_scene_audio FOREIGN KEY (audio_id) REFERENCES audio_records(audio_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS timeline_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  event_id CHAR(36) NOT NULL UNIQUE,
  audio_id VARCHAR(64) NOT NULL,
  title VARCHAR(128) NOT NULL,
  trigger_time DATETIME NOT NULL,
  status ENUM('PENDING','COMPLETED','OVERDUE') NOT NULL DEFAULT 'PENDING',
  clue_segment_id INT NULL,
  notify_offset INT NOT NULL DEFAULT 15,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_event_due (status, trigger_time),
  CONSTRAINT fk_event_audio FOREIGN KEY (audio_id) REFERENCES audio_records(audio_id) ON DELETE CASCADE
);
